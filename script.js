/** Format a YYYY-MM-DD string to a human-readable date like "March 17, 2026" */
function formatDate(dateStr) {
  const [year, month, day] = dateStr.split('-').map(Number);
  return new Date(year, month - 1, day).toLocaleDateString('en-US', {
    year: 'numeric', month: 'long', day: 'numeric',
  });
}

/* =====================================================
   WORD SELECTION
   ===================================================== */

/**
 * Pick the daily word deterministically using the current date as a seed.
 * All players share the same word on the same calendar day.
 */
function getDailyWord() {
  const epoch    = new Date('2024-01-01').getTime();
  const now      = new Date(todayKey()).getTime();
  const dayIndex = Math.floor((now - epoch) / 86_400_000);
  // Use seeded RNG so the selection is not simply dayIndex % length,
  // making the cycling less predictable and more evenly distributed.
  const rand = seededRandom(dayIndex * 1_234_567 + 9_876_543);
  const idx  = Math.floor(rand * WINNING_WORDS.length);
  return WINNING_WORDS[idx].toUpperCase();
}

/**
 * Pick the next word for continuous play mode.
 * Tracks which words have already been used via localStorage.
 * When all words are exhausted the list reshuffles and starts again.
 *
 * @returns {{ word: string, wordNumber: number, totalWords: number }}
 */
function getContinuousWordInfo() {
  const total = WINNING_WORDS.length;
  let contState = loadContinuousIndex();

  // Build a shuffled order if we don't have one or have exhausted it
  if (!contState.order || contState.order.length === 0) {
    contState.order    = shuffleIndices(total, contState.generation);
    contState.position = 0;
    // Increment generation after first use so the next reshuffle uses a new seed
    contState.generation = contState.generation + 1;
  }

  const idx     = contState.order[contState.position];
  // wordNum counts from 1 across all generations:
  //   generation 1, position 0 → word 1
  //   generation 1, position 299 → word 300
  //   generation 2, position 0  → word 301
  const wordNum = contState.position + 1 + (contState.generation - 2) * total;
  return {
    word:       WINNING_WORDS[idx].toUpperCase(),
    wordNumber: wordNum,
    totalWords: total,
    contState,
  };
}

/**
 * Produce a deterministically shuffled array of indices [0..n-1].
 * @param {number} n           Number of words
 * @param {number} generation  Shuffle generation (increments each cycle)
 * @returns {number[]}
 */
function shuffleIndices(n, generation) {
  const arr = Array.from({ length: n }, (_, i) => i);
  // Fisher-Yates with seeded RNG
  for (let i = n - 1; i > 0; i--) {
    const seed = generation * 999_983 + i * 1_000_003;
    const j    = Math.floor(seededRandom(seed) * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

