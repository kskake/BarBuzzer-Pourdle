/**
 * Core evaluation: returns array of { letter, state } objects
 * Handles duplicate letters correctly.
 */
function evaluateGuess(guess) {
  const result = Array.from({ length: WORD_LENGTH }, (_, i) => ({
    letter: guess[i],
    state: 'absent',
  }));

  // Track unmatched target letters for "present" detection
  const targetCounts = {};
  for (let i = 0; i < WORD_LENGTH; i++) {
    const ch = TARGET_WORD[i];
    if (guess[i] !== ch) {
      targetCounts[ch] = (targetCounts[ch] || 0) + 1;
    }
  }

  // First pass: mark correct positions
  for (let i = 0; i < WORD_LENGTH; i++) {
    if (guess[i] === TARGET_WORD[i]) {
      result[i].state = 'correct';
    }
  }

  // Second pass: mark present (wrong position)
  for (let i = 0; i < WORD_LENGTH; i++) {
    if (result[i].state === 'correct') continue;
    const ch = guess[i];
    if (targetCounts[ch] > 0) {
      result[i].state = 'present';
      targetCounts[ch]--;
    }
  }

  return result;
}

/**
 * Render a completed guess row with tile flip animations.
 * @param {string}  guess   - 5-letter uppercase string
 * @param {number}  row     - row index 0-5
 * @param {boolean} animate - whether to use flip animation
 */
function renderGuess(guess, row, animate = true) {
  const evaluation = evaluateGuess(guess);
  const tiles = tileRows[row];

  evaluation.forEach(({ letter, state: tileState }, col) => {
    const tile = tiles[col];
    tile.textContent = letter;

    const applyState = () => { tile.dataset.state = tileState; };

    if (animate) {
      setTimeout(applyState, col * 120);
    } else {
      applyState();
    }

    // Update keyboard colour (only upgrade: correct > present > incorrect)
    // Absent tiles stay dark gray, but keyboard keys for absent letters turn dark red.
    const keyEl = keyMap.get(letter);
    if (keyEl) {
      const current  = keyEl.dataset.state;
      const keyState = tileState === 'absent' ? 'incorrect' : tileState;
      const priority = { correct: 3, present: 2, incorrect: 1, undefined: 0 };
      if ((priority[keyState] || 0) > (priority[current] || 0)) {
        if (animate) {
          setTimeout(() => { keyEl.dataset.state = keyState; }, col * 120 + 300);
        } else {
          keyEl.dataset.state = keyState;
        }
      }
    }
  });
}

/** Handle a key press (letter, ENTER, or ⌫) */
function handleKey(key) {
  // Guard against midnight rollover before processing any input.
  checkDayRollover();
  if (state.gameOver) return;

  if (key === '⌫' || key === 'BACKSPACE') {
    if (currentInput.length > 0) {
      currentInput.pop();
      updateCurrentRow();
    }
    return;
  }

  if (key === 'ENTER') {
    submitGuess();
    return;
  }

  // Single letter
  if (/^[A-Z]$/.test(key) && currentInput.length < WORD_LENGTH) {
    currentInput.push(key);
    updateCurrentRow();
  }
}

/** Reflect currentInput in the active board row */
function updateCurrentRow() {
  const tiles = tileRows[currentRow];
  for (let c = 0; c < WORD_LENGTH; c++) {
    const tile = tiles[c];
    if (c < currentInput.length) {
      tile.textContent   = currentInput[c];
      tile.dataset.state = 'tbd';
    } else {
      tile.textContent   = '';
      tile.dataset.state = 'empty';
    }
  }
}

/** Shake the current row to signal an invalid input */
function shakeRow(row) {
  const tiles = tileRows[row];
  tiles.forEach(tile => {
    tile.classList.remove('row-shake');
    void tile.offsetWidth; // force reflow to restart animation
    tile.classList.add('row-shake');
    tile.addEventListener('animationend', () => tile.classList.remove('row-shake'), { once: true });
  });
}

/** Bounce winning row tiles */
function bounceRow(row) {
  tileRows[row].forEach((tile, i) => {
    setTimeout(() => {
      tile.classList.add('tile-bounce');
      tile.addEventListener('animationend', () => tile.classList.remove('tile-bounce'), { once: true });
    }, i * 100);
  });
}

/** Submit the current round */
function submitGuess() {
  if (inputLocked) return;
  if (currentInput.length < WORD_LENGTH) {
    showToast('Not enough letters');
    shakeRow(currentRow);
    return;
  }

  const guess = currentInput.join('');

  // Validate word
  if (!VALID_GUESSES.has(guess)) {
    showToast('Not a valid word');
    shakeRow(currentRow);
    return;
  }

  // Render the round with pour animations
  renderGuess(guess, currentRow, true);

  // Save to state
  state.guesses.push(guess);
  const won = guess === TARGET_WORD;

  if (won) {
    state.gameOver = true;
    state.won      = true;
    persistState();
    lockInput();
    const pourDelay = WORD_LENGTH * 120 + 400;
    const roundsUsed = state.guesses.length;
    setTimeout(() => bounceRow(currentRow), pourDelay);
    setTimeout(() => {
      awardPourDleXP(roundsUsed);
      showModal(true, TARGET_WORD);
    }, pourDelay + 500);
    setTimeout(() => showToast("Cheers! That's on the house. 🍻", 2200), pourDelay);
  } else {
    currentRow++;
    currentInput = [];
    persistState();

    if (currentRow >= MAX_GUESSES) {
      state.gameOver = true;
      persistState();
      lockInput();
      const pourDelay = WORD_LENGTH * 120 + 500;
      setTimeout(() => showModal(false, TARGET_WORD), pourDelay);
    }
  }
}

/* =====================================================
   PHYSICAL KEYBOARD SUPPORT
   ===================================================== */
document.addEventListener('keydown', e => {
  if (e.ctrlKey || e.metaKey || e.altKey) return;
  const key = e.key.toUpperCase();
  if (key === 'BACKSPACE') { handleKey('⌫'); return; }
  if (key === 'ENTER')     { handleKey('ENTER'); return; }
  if (/^[A-Z]$/.test(key)) { handleKey(key); return; }
});
